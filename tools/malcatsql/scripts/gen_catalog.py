"""Regenerate the schema catalog and SQL function reference from a live malcatsql session.

    python scripts/gen_catalog.py [binary]      (default: C:\\Windows\\System32\\notepad.exe)

Writes:
    plugins/malcatsql/skills/connect/references/schema-catalog.md
    plugins/malcatsql/skills/functions/references/function-catalog.md
"""

from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from malcatsql import __version__  # noqa: E402
from malcatsql.engine import SETTING_SPECS, Engine  # noqa: E402
from malcatsql.functions import CATALOG  # noqa: E402
from malcatsql.session import Session  # noqa: E402
from malcatsql.tables import VIEWS  # noqa: E402
from malcatsql.workspace import WORKSPACE_FUNCTIONS  # noqa: E402

SKILLS = ROOT.parents[1] / "plugins" / "malcatsql" / "skills"  # ROOT = <market>/tools/malcatsql


def md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def schema_catalog(engine: Engine) -> str:
    out = [
        "# Schema Catalog (malcatsql)",
        "",
        f"Generated by `scripts/gen_catalog.py` from a live malcatsql {__version__} session.",
        "**Confirm the live shape with `PRAGMA table_xinfo(<table>);`** before complex queries.",
        "",
        "Conventions: every `addr`/`*_addr` column is a **virtual address** (what Malcat prints in",
        "disassembly and pseudo-C; print with `hex()`). It is NULL for locations without a VA",
        "(e.g. overlay bytes). `ea` columns are Malcat's internal effective addresses, and `offset` columns",
        "are file offsets.",
        "",
        "## Refresh",
        "",
        "```sql",
        "SELECT name, type FROM pragma_table_list WHERE schema IN ('main','temp') ORDER BY type, name;",
        "PRAGMA table_xinfo(<surface>);",
        "```",
        "",
        "## Owner-skill mapping",
        "",
        "| Surface | Kind | Skill | Writable | Pushdown (EQ) | Notes |",
        "|---------|------|-------|----------|---------------|-------|",
    ]
    for name, surf in sorted(engine.surfaces.items()):
        writable = ", ".join(op for op in ("insert", "update", "delete") if op in surf.writable) or "-"
        pushdown = ", ".join(f"`{c.name}`" for c in surf.columns if c.pushdown and not c.hidden) or "-"
        note = surf.doc
        if surf.scan_error:
            note += " Unconstrained scan is an error."
        out.append(f"| `{name}` | table | `{surf.skill}` | {writable} | {pushdown} | {md_escape(note)} |")
    view_skill = {"callers": "xrefs", "callees": "xrefs", "import_refs": "xrefs", "string_refs": "data", "entities": "analysis"}
    for name in sorted(VIEWS):
        out.append(f"| `{name}` | view | `{view_skill.get(name, 'connect')}` | - | via base tables | |")
    out += ["", "## Columns", ""]
    for name in engine.table_names():
        out.append(f"### `{name}`")
        out.append("")
        surf = engine.surfaces.get(name)
        docs = {c.name: c.doc for c in surf.columns} if surf else {}
        out.append("| Column | Type | Notes |")
        out.append("|--------|------|-------|")
        for cid, col, ctype, _nn, _d, _pk, hidden in engine.schema_of(name):
            notes = []
            if hidden:
                notes.append("hidden input")
            if surf:
                spec = next(c for c in surf.columns if c.name == col)
                if spec.required:
                    notes.append("required")
                if spec.pushdown and not hidden:
                    notes.append("EQ pushdown")
            if docs.get(col):
                notes.append(docs[col])
            out.append(f"| `{col}` | {ctype or ''} | {md_escape('; '.join(notes))} |")
        out.append("")
    out += [
        "## `runtime_settings` keys",
        "",
        "| Key | Type | Default | Description |",
        "|-----|------|---------|-------------|",
    ]
    for spec in SETTING_SPECS:
        out.append(f"| `{spec.key}` | {spec.type} | `{spec.default}` | {spec.doc} |")
    out += ["", "## `capabilities` rows", "", "| Key | Value | Note |", "|-----|-------|------|"]
    for key, value, desc in engine.conn.execute("SELECT key, value, description FROM capabilities"):
        if key.startswith("mutation.") and value == "false":
            continue
        out.append(f"| `{key}` | {value} | {md_escape(desc or '')} |")
    out += ["", "All other `mutation.<table>.<op>` rows are `false`; a write to them fails with that key in the error.", ""]
    return "\n".join(out)


def function_catalog() -> str:
    out = [
        "# SQL Function Catalog (malcatsql)",
        "",
        f"Generated by `scripts/gen_catalog.py` (malcatsql {__version__}). Address arguments are virtual",
        "addresses (integers such as `0x1400019C0`, or `'0x1400019C0'` text).",
        "",
        "| Function | Arities | Description |",
        "|----------|---------|-------------|",
    ]
    for name in sorted(CATALOG):
        arities, doc = CATALOG[name]
        out.append(f"| `{name}` | {arities} | {md_escape(doc)} |")
    out += [
        "",
        "## Workspace-only functions",
        "",
        "Available on the connection of a multi-sample workspace (see the `workspace` skill), where",
        "`hex()` and `hamming()` also exist. Inside each sample every function above works unchanged.",
        "",
        "| Function | Arities | Description |",
        "|----------|---------|-------------|",
    ]
    for name, (arities, doc) in sorted(WORKSPACE_FUNCTIONS.items()):
        out.append(f"| `{name}` | {arities} | {md_escape(doc)} |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(r"C:\Windows\System32\notepad.exe")
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / src.name
        shutil.copyfile(src, copy)
        engine = Engine(Session(copy, use_project=False))
        (SKILLS / "connect" / "references").mkdir(parents=True, exist_ok=True)
        (SKILLS / "functions" / "references").mkdir(parents=True, exist_ok=True)
        (SKILLS / "connect" / "references" / "schema-catalog.md").write_text(schema_catalog(engine), encoding="utf-8")
        (SKILLS / "functions" / "references" / "function-catalog.md").write_text(function_catalog(), encoding="utf-8")
        engine.conn.close()
    print("catalogs written under", SKILLS)


if __name__ == "__main__":
    main()
